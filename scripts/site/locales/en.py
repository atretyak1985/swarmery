# English strings for the site templates in scripts/site/build.py.
#
# Every literal that a reader sees (or a screen reader hears) lives here, keyed by
# a lowercase dotted name; build.py reads it through T(key). Values are trusted
# HTML fragments: <em>, <code>, <b> and links are allowed and are written as-is,
# EXCEPT the keys in ESCAPED_KEYS below.
#
# ESCAPED_KEYS are plain text: build.py HTML-escapes them at the call site, so
# markup or an entity in them would show up literally (a translation that has
# some stops the build). They reach the page three ways:
#   - TE(key), the escaping T(): every *_aria label, js.copied / js.chapters
#     (data-i18n-* attributes), dialog.close, ep.label (data-title) and
#     home.reel.<stage> (the reel tab text), videos.voice_note (after the
#     videos lede). TE() refuses any key not listed.
#   - head(title, desc): *.meta.title, *.meta.desc and the nav.<page> names
#     that page titles are built from (escaped as part of the composed string).
#   - clip(..., url): home.market.clip and feature.silent (the clip aria-label).
# A key escaped one way may still be written as a plain T() text node elsewhere
# (nav.features, ep.label); plain text is safe there too.
#
# Placeholders: "%d" for ep.label (printf style), {name}/{repo} elsewhere
# (str.format). Feature, promo, caption, principle and post copy is content, not
# UI: it stays in data.py, and a translation of it goes into <lang>.CONTENT.
#
# A language other than English merges its own UI over this one; any key it does
# not define falls back to English and is reported (build.py --strict fails).

